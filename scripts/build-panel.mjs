// Regenerates src/panel_html.ts from panel/index.html (run after editing the panel UI)
import { readFileSync, writeFileSync } from 'node:fs';
const html = readFileSync(new URL('../panel/index.html', import.meta.url), 'utf8');
writeFileSync(
  new URL('../src/panel_html.ts', import.meta.url),
  `// generated by scripts/build-panel.mjs -- do not edit by hand\nexport const PANEL_HTML = ${JSON.stringify(html)};\n`,
);
console.log('src/panel_html.ts written');
